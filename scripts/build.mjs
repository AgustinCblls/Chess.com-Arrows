// Genera, desde src/, el userscript y el content script de la extensión.
// chess_analysis_arrows.user.js y chrome-extension/content.js son el mismo archivo, byte a byte.
// La versión sale de package.json y se escribe también en el manifest.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const root = new URL('../', import.meta.url);
export const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
export const version = pkg.version;

const header = `// ==UserScript==
// @name         Chess.com - Top 3 Analysis Arrows
// @namespace    https://github.com/hediondom/Chess.com-Arrows
// @version      ${version}
// @description  Top-3 engine move arrows for chess.com analysis and watched games. Uses chess.com's own Stockfish in a Web Worker, so no extra app or Stockfish install is needed.
// @homepageURL  https://github.com/hediondom/Chess.com-Arrows
// @supportURL   https://github.com/hediondom/Chess.com-Arrows/issues
// @downloadURL  https://github.com/hediondom/Chess.com-Arrows/raw/main/chess_analysis_arrows.user.js
// @updateURL    https://github.com/hediondom/Chess.com-Arrows/raw/main/chess_analysis_arrows.user.js
// @match        https://www.chess.com/*
// @run-at       document-idle
// @grant        none
// ==/UserScript==
`;

const notice = '// Generated from src/ by scripts/build.mjs. Do not edit this file: edit src/ and run "npm run build".\n';

// store: true = compilación para tiendas (sin motores de CDN; solo el de chess.com y el incluido)
export async function bundle({ store = false } = {}) {
  const result = await build({
    entryPoints: [fileURLToPath(new URL('src/main.js', root))],
    bundle: true,
    format: 'iife',
    target: ['chrome110', 'firefox128', 'safari16'],
    charset: 'utf8',
    legalComments: 'none',
    minifySyntax: store, // quita del todo las ramas muertas (las URL de CDN)
    define: { __VERSION__: JSON.stringify(version), __STORE_BUILD__: String(store) },
    write: false
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = header + notice + await bundle();
  writeFileSync(new URL('chess_analysis_arrows.user.js', root), code);
  writeFileSync(new URL('chrome-extension/content.js', root), code);

  const manifestUrl = new URL('chrome-extension/manifest.json', root);
  const manifest = JSON.parse(readFileSync(manifestUrl, 'utf8'));
  manifest.version = version;
  writeFileSync(manifestUrl, JSON.stringify(manifest, null, 2) + '\n');

  console.log('built v' + version + ' (' + Math.round(code.length / 1024) + ' KB)');
}
